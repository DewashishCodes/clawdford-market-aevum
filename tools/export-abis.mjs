// Writes packages/aevum/src/abis.ts from Foundry artifacts so TypeScript gets typed ABIs without a forge build.
// Run after contract changes: `pnpm export-abis` (needs `forge build` first).
import { readFileSync, writeFileSync } from "node:fs";

const CONTRACTS = ["AgentVault", "StallRegistry", "IdentityRegistry", "ReputationRegistry", "MockTUSD8"];
const root = new URL("../", import.meta.url);

let out = "// Generated by tools/export-abis.mjs. Do not edit.\n";
for (const name of CONTRACTS) {
  const { abi } = JSON.parse(readFileSync(new URL(`contracts/out/${name}.sol/${name}.json`, root), "utf8"));
  const id = name[0].toLowerCase() + name.slice(1);
  out += `\nexport const ${id}Abi = ${JSON.stringify(abi)} as const;\n`;
}
writeFileSync(new URL("packages/aevum/src/abis.ts", root), out);
console.log(`wrote abis for ${CONTRACTS.join(", ")}`);
